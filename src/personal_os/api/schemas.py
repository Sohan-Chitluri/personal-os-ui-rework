"""Pydantic schemas for the Personal OS API (M1-C).

Follows the conventions in docs/API_CONTRACT.md and maps cleanly to the
M1-A domain models and service layer interfaces.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, model_validator

# --------------------------------------------------------------------------
# Problem Details (RFC 7807)
# --------------------------------------------------------------------------


class ProblemDetail(BaseModel):
    """RFC 7807 Problem Details representation for HTTP error responses."""

    type: str = Field(
        default="about:blank",
        description="URI reference identifying the problem type.",
    )
    title: str = Field(
        ...,
        description="Short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="HTTP status code generated by the origin server.",
    )
    detail: str | None = Field(
        default=None,
        description="Human-readable explanation specific to this occurrence.",
    )
    instance: str | None = Field(
        default=None,
        description="URI reference identifying the specific occurrence of the problem.",
    )
    extensions: dict[str, Any] = Field(
        default_factory=dict,
        description="Additional structured problem information.",
    )


