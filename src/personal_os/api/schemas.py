class TaskCreate(BaseModel):
    title: str = Field(..., min_length=1, max_length=512, description="Task title")
    project_id: str | None = Field(default=None, description="Associated project ID")
    description: str | None = Field(default=None, max_length=5000, description="Task description")
    priority: int | None = Field(
        default=None, ge=1, le=5, description="Priority rating (1 highest)"
    )
    due_date: datetime | None = Field(
        default=None, description="Due date and time in ISO 8601 (soft deadline)"
    )
    soft_deadline: datetime | None = Field(
        default=None, description="Intended soft deadline target"
    )
    hard_deadline: datetime | None = Field(
        default=None, description="External or fixed hard deadline constraint"
    )

    @model_validator(mode="before")
    @classmethod
    def sync_deadlines(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if data.get("soft_deadline") is not None and data.get("due_date") is None:
                data["due_date"] = data["soft_deadline"]
            elif data.get("due_date") is not None and data.get("soft_deadline") is None:
                data["soft_deadline"] = data["due_date"]
        return data


class TaskUpdate(BaseModel):
    title: str | None = Field(
        default=None, min_length=1, max_length=512, description="Updated title"
    )
    project_id: str | None = Field(default=None, description="Updated project ID")
    description: str | None = Field(
        default=None, max_length=5000, description="Updated description"
    )
    status: str | None = Field(default=None, description="Updated status (open, done, etc.)")
    priority: int | None = Field(default=None, ge=1, le=5, description="Updated priority rating")
    due_date: datetime | None = Field(default=None, description="Updated due date")
    soft_deadline: datetime | None = Field(default=None, description="Updated soft deadline")
    hard_deadline: datetime | None = Field(default=None, description="Updated hard deadline")

    @model_validator(mode="before")
    @classmethod
    def sync_deadlines(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "soft_deadline" in data and "due_date" not in data:
                data["due_date"] = data["soft_deadline"]
            elif "due_date" in data and "soft_deadline" not in data:
                data["soft_deadline"] = data["due_date"]
        return data


class TaskResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    owner_id: str
    project_id: str | None = None
    capture_id: str | None = None
    title: str
    description: str | None = None
    status: str
    priority: int | None = None
    due_date: datetime | None = None
    soft_deadline: datetime | None = None
    hard_deadline: datetime | None = None
    revision: int
    created_at: datetime
    updated_at: datetime

    @model_validator(mode="after")
    def sync_soft_deadline(self) -> TaskResponse:
        if self.soft_deadline is None and self.due_date is not None:
            self.soft_deadline = self.due_date
        elif self.due_date is None and self.soft_deadline is not None:
            self.due_date = self.soft_deadline
        return self


class TaskListResponse(BaseModel):
    items: list[TaskResponse]
    total: int


