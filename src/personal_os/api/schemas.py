class CaptureCreate(BaseModel):
    content: str | None = Field(
        default=None, min_length=1, max_length=10000, description="Raw capture content"
    )
    raw_text: str | None = Field(
        default=None, min_length=1, max_length=10000, description="Alias for content"
    )
    source: str = Field(default="web", description="Capture source (web, cli, voice, api)")
    content_type: str = Field(default="text", description="MIME or format type (text, audio, etc.)")
    project_id: str | None = Field(default=None, description="Optional target project ID")
    idempotency_key: str | None = Field(
        default=None, max_length=128, description="Client idempotency key"
    )

    @model_validator(mode="before")
    @classmethod
    def normalize_content(cls, data: Any) -> Any:
        if isinstance(data, dict):
            content = data.get("content") or data.get("raw_text")
            if not content:
                raise ValueError("Field 'content' or 'raw_text' is required")
            data["content"] = content
        return data


