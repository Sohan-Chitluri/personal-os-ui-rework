# BackgroundProcessor — async queue + semantic pipeline
# ─────────────────────────────────────────────────────────────────────────────

class BackgroundProcessor:
    """Background processor that handles entry processing asynchronously.

    Primary path (OPENROUTER_API_KEY set):
        SemanticExtractor → typed VaultActions → KnowledgeApplier.apply_action()
        → vault.append_semantic_block()

    Fallback (OPENROUTER_API_KEY unset or LLMProviderError):
        KnowledgeExtractor (regex) → KnowledgeApplier.apply(dict)
        Logged as a warning — no crash.
    """

    def __init__(self, vault: VaultManager, on_processed=None):
        self.vault = vault
        self.extractor = KnowledgeExtractor(vault)
        self.applier = KnowledgeApplier(vault)
        self._queue: asyncio.Queue = asyncio.Queue()
        self._worker_task: Optional[asyncio.Task] = None
        self._running = False
        self._on_processed = on_processed

    async def start(self):
        self._running = True
        self._worker_task = asyncio.create_task(self._worker())
        logger.info("Background processor started")

    async def stop(self):
        self._running = False
        if self._worker_task:
            self._worker_task.cancel()
            try:
                await self._worker_task
            except asyncio.CancelledError:
                pass
        logger.info("Background processor stopped")

    async def process(self, text: str, source: str = "Text", capture_id: str = "") -> ProcessingResult:
        """Process an entry immediately (TUI foreground path)."""
        return await self._process_entry(text, source, capture_id=capture_id)

    async def queue(self, text: str, source: str = "Text", capture_id: str = ""):
        """Queue an entry for background processing."""
        await self._queue.put((text, source, capture_id))

    async def _worker(self):
        while self._running:
            try:
                item = await asyncio.wait_for(self._queue.get(), timeout=1.0)
                if len(item) == 3:
                    text, source, capture_id = item
                else:
                    text, source = item
                    capture_id = ""
                result = await self._process_entry(text, source, capture_id=capture_id)
                self._queue.task_done()
                if self._on_processed:
                    try:
                        res = self._on_processed(result, text, source)
                        if inspect.isawaitable(res):
                            await res
                    except Exception as e:
                        logger.error("on_processed callback error: %s", e)
            except asyncio.TimeoutError:
                continue
            except Exception as e:
                logger.error("Background processor error: %s", e)

    async def _process_entry(self, text: str, source: str, capture_id: str = "") -> ProcessingResult:
        """Process a single entry — semantic path with regex fallback."""
        result = ProcessingResult()

        if os.environ.get("OPENROUTER_API_KEY"):
            try:
                return await self._process_semantic(text, source, capture_id, result)
            except Exception as exc:
                logger.warning("Semantic pipeline failed, falling back to regex: %s", exc)
                result.errors.append(f"Semantic pipeline error (using regex fallback): {exc}")
        else:
            logger.debug("OPENROUTER_API_KEY not set — using regex extractor")

        return self._process_regex(text, source, result)

    async def _process_semantic(
        self, text: str, source: str, capture_id: str, result: ProcessingResult
    ) -> ProcessingResult:
        from personal_os.core.extraction import SemanticExtractor, ExtractionContext
        from personal_os.core.llm import get_provider

        config = get_config()
        provider = get_provider(config)

        projects = [p['name'] for p in self.vault.list_projects()]
        recent_raw = [
            e.get('content', '') for e in self.vault.get_journal_entries()[-5:]
            if not e.get('is_semantic')
        ]
        ctx = ExtractionContext(
            now=datetime.now(),
            timezone="UTC",
            projects=projects,
            recent_captures=recent_raw,
            active_tasks=[],
            current_project=None,
        )

        extractor = SemanticExtractor(provider=provider)
        capture_result = await extractor.extract(
            text, context=ctx, capture_id=capture_id, source=source
        )
        await provider.close()

        result.items = capture_result.items
        result.errors.extend(capture_result.errors)

        # Batch processing-stage vault writes (semantic actions + semantic block)
        # The journal entry (raw capture) was already committed by persist_capture()
        # before this method was called.
        self.vault.begin_batch(message=f"Semantic processing [{capture_id[:8]}]")
        try:
            for item in capture_result.vault_writes:
                try:
                    changes = self.applier.apply_action(item.action)
                    result.changes_made.extend(changes)
                except Exception as exc:
                    logger.error("apply_action failed for %s: %s", type(item.action).__name__, exc)
                    result.errors.append(f"Action apply error: {exc}")
                    raise  # Re-raise to trigger rollback

            if capture_id and capture_result.items:
                try:
                    self.vault.append_semantic_block(
                        capture_id,
                        capture_result.to_semantic_block_items(),
                        processed_at=datetime.now(),
                    )
                except Exception as exc:
                    logger.error("append_semantic_block failed: %s", exc)
                    result.errors.append(f"Semantic block write error: {exc}")
                    raise  # Re-raise to trigger rollback

            self.vault.commit_batch()
        except Exception:
            self.vault.rollback_batch()
            raise

        return result

    def _process_regex(self, text: str, source: str, result: ProcessingResult) -> ProcessingResult:
        extractions = self.extractor.extract(text)
        result.extractions = extractions
        for ext in extractions:
            changes = self.applier.apply(ext)
            result.changes_made.extend(changes)
        return result


async def process_entry(text: str, source: str = "Text") -> ProcessingResult:
    """Convenience function to process an entry (CLI one-shot path)."""
    vault = get_vault()
    processor = BackgroundProcessor(vault)
    return await processor.process(text, source)
