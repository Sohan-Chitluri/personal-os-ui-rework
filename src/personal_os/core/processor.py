"""Background processor — extracts knowledge from entries automatically.

Processing pipeline:
    BackgroundProcessor._process_entry(text, source, capture_id)
        ↓ (primary path — if OPENROUTER_API_KEY is set)
    SemanticExtractor.extract(text, ExtractionContext, capture_id)
        ↓
    KnowledgeApplier.apply_action(VaultAction) for each vault_write
        ↓
    vault.append_semantic_block(capture_id, items)
        ↓ (fallback — if OPENROUTER_API_KEY unset or LLMProviderError)
    KnowledgeExtractor (regex) → KnowledgeApplier.apply(dict)

capture_id is generated by persist_capture (in capture.py) and passed here so
the semantic block is linked to the exact raw journal entry by the same ULID.
"""
