class KnowledgeApplier:
    """Applies extractions to vault files.

    Two entrypoints:
    - apply_action(VaultAction) — typed path from SemanticExtractor
    - apply(dict) — legacy dict path from regex KnowledgeExtractor (fallback)
    """

    def __init__(self, vault: VaultManager):
        self.vault = vault

    # ------------------------------------------------------------------ typed

    def apply_action(self, action: Any) -> List[str]:
        """Apply a typed VaultAction from the semantic pipeline."""
        from personal_os.core.extraction.actions import (
            CreateTask, CreatePossibleTask, RecordProgress, RecordActivity,
            RecordProblem, AddDecision, MarkComplete, AppendLearning,
            AppendNote, NoOp,
        )

        if isinstance(action, NoOp):
            logger.debug("NoOp: %s", action.reason)
            return []

        if isinstance(action, CreateTask):
            return self._action_create_task(action)

        if isinstance(action, CreatePossibleTask):
            return self._action_create_possible_task(action)

        if isinstance(action, RecordProgress):
            return self._action_record_progress(action)

        if isinstance(action, RecordActivity):
            if action.project is None:
                return []  # NoOp: Daily Stream is sufficient
            return self._action_record_activity(action)

        if isinstance(action, RecordProblem):
            if action.project is None:
                return []  # NoOp: Daily Stream is sufficient
            return self._action_record_problem(action)

        if isinstance(action, AddDecision):
            return self._action_add_decision(action)

        if isinstance(action, MarkComplete):
            return self._action_mark_complete(action)

        if isinstance(action, AppendLearning):
            return self._action_append_learning(action)

        if isinstance(action, AppendNote):
            if action.project is None:
                return []  # NoOp
            return self._action_append_note(action)

        logger.warning("Unknown VaultAction type: %s", type(action).__name__)
        return []

    def _action_create_task(self, action: Any) -> List[str]:
        project = action.project
        cid_tag = f" *(cid: {action.capture_id})*" if action.capture_id else ""
        deadline_tag = f" 📅 {action.deadline}" if action.deadline else ""
        entry = f"- [ ] {action.title}{deadline_tag}{cid_tag}\n"

        if project:
            tasks_file = self.vault.config.projects_dir / project / "Tasks.md"
            if not tasks_file.exists():
                return [f"⚠️ No Tasks.md found in {project}"]
            content = self.vault.read_file(tasks_file)
            content = self._insert_under_section(content, "## Active Tasks", entry)
            self.vault.write_file(tasks_file, content, message=f"Task: {action.title[:50]}")
            return [f"📝 Added task to {project}/Tasks.md"]
        else:
            inbox_file = self.vault.config.inbox_dir / "Tasks.md"
            inbox_file.parent.mkdir(parents=True, exist_ok=True)
            content = self.vault.read_file(inbox_file) if inbox_file.exists() else "# Inbox Tasks\n\n## Active Tasks\n"
            content = self._insert_under_section(content, "## Active Tasks", entry)
            self.vault.write_file(inbox_file, content, message=f"Inbox task: {action.title[:50]}")
            return [f"📥 Added task to Inbox: {action.title[:60]}"]

